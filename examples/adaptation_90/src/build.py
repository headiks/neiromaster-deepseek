def esc(s):
    return html.escape(s, quote=False)


def F(label=""):
    """Поле для заполнения данными предприятия."""
    return f'<span class="fill">{esc(label)}&nbsp;</span>'


def msg(*paras):
    return '<div class="msg">' + "".join(f"<p>{p}</p>" for p in paras) + "</div>"


def cb(*items):
    return '<ul class="cb">' + "".join(f"<li>{i}</li>" for i in items) + "</ul>"


def ul(*items):
    return "<ul>" + "".join(f"<li>{i}</li>" for i in items) + "</ul>"


def table(head, rows):
    h = "".join(f"<th>{c}</th>" for c in head)
    b = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    return f"<table><tr>{h}</tr>{b}</table>"


def quiz(qs, passing):
    """qs: [(вопрос, [варианты], индекс_верного, пояснение)]"""
    out = [f'<p class="note">Проходной результат: {passing}. Верный ответ отмечен, пояснение показывается сотруднику после ответа.</p>']
    for n, (q, opts, ok, ex) in enumerate(qs, 1):
        lis = "".join(
            f'<li class="{"ok" if i == ok else ""}">{"абвгд"[i]}) {o}</li>' for i, o in enumerate(opts))
        out.append(f'<div class="q"><b>{n}. {q}</b><ol>{lis}</ol><div class="expl">Пояснение: {ex}</div></div>')
    return "".join(out)


SCALE = '<span class="scale">① ② ③ ④ ⑤</span>'


def survey(*items):
    """items: строки-вопросы; префикс 'S:' — шкала 1–5, 'T:' — свободный ответ, 'C:вопрос|a|b|c' — выбор."""
    out = ["<ol>"]
    for it in items:
        kind, text = it[:2], it[2:]
        if kind == "S:":
            out.append(f"<li>{text}<br>{SCALE} <span class='note'>(1 — очень плохо, 5 — отлично)</span></li>")
        elif kind == "C:":
            q, *opts = text.split("|")
            out.append(f"<li>{q}<br>" + " &nbsp; ".join(f"☐ {o}" for o in opts) + "</li>")
        else:
            out.append(f"<li>{text}<div class='line'></div></li>")
    out.append("</ol>")
    return "".join(out)


def sub(when, title, kind, body, long=False):
    cls, who = KIND[kind]
    return (f'<div class="sub{" long" if long else ""}"><h3>{esc(title)}</h3>'
            f'<div class="meta"><span><b>Когда:</b> {esc(when)}</span>'
            f'<span class="tag {cls}">{esc(kind)}</span><span>{esc(who)}</span></div>{body}</div>')


def stage_doc(num, name, period, goal, rows, body, result):
    summary = table(["Когда", "Подэтап", "Тип"], rows)
    return (f'<div class="cover"><div class="kicker">План адаптации · 90 дней · Этап {num}</div>'
            f'<h1>{esc(name)}</h1><div class="lead">{esc(period)}</div></div>'
            f'<div class="goal"><b>Цель этапа.</b> {goal}</div>'
            f"<h2>Состав этапа</h2>{summary}<h2>Содержание подэтапов</h2>{body}"
            f"<h2>Результат этапа</h2>{result}")


def signs(*roles):
    cells = "".join(f"<tr><td>{r}</td><td>____________________ / ____________________</td><td>«___» ________ 20__</td></tr>" for r in roles)
    return f'<table class="sign">{cells}</table>'


