def main():
    exe = next((b for b in BROWSERS if os.path.exists(b)), None) or shutil.which("chrome") or shutil.which("msedge")
    if not exe:
        raise SystemExit("Не найден Chrome/Edge для печати PDF")
    tmp = tempfile.mkdtemp()
    for name, title, body in DOCS:
        src = os.path.join(tmp, "doc.html")
        with open(src, "w", encoding="utf-8") as f:
            f.write(f'<!doctype html><html lang="ru"><head><meta charset="utf-8"><title>{esc(title)}</title>'
                    f"<style>{CSS}</style></head><body>{body}</body></html>")
        pdf = os.path.join(tmp, "doc.pdf")  # ASCII-путь для браузера, потом переименовываем
        subprocess.run([exe, "--headless=new", "--disable-gpu", "--no-pdf-header-footer",
                        f"--print-to-pdf={pdf}", "file:///" + src.replace("\\", "/")],
                       check=True, capture_output=True, timeout=120)
        shutil.move(pdf, os.path.join(OUT, name + ".pdf"))
        print("OK", name)
    shutil.rmtree(tmp, ignore_errors=True)


if __name__ == "__main__":
    main()
